import puppeteer from 'puppeteer-core'
import { mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'

const output = resolve(process.cwd(), '../../artifacts/scheduled-tasks-preview')
await mkdir(output, { recursive: true })
const browser = await puppeteer.launch({ executablePath: process.env.CHROMIUM_PATH ?? '/snap/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-gpu'] })
const errors = []
try {
  const page = await browser.newPage()
  await page.setViewport({ width: 1440, height: 900, deviceScaleFactor: 1 })
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setRequestInterception(true)
  page.on('request', (request) => {
    if (new URL(request.url()).origin !== 'http://127.0.0.1:4182') void request.abort()
    else void request.continue()
  })
  await page.goto('http://127.0.0.1:4182/?preview=scheduled-tasks', { waitUntil: 'networkidle0' })
  await page.waitForSelector('[data-testid="schedule-plan-panel"]')
  await page.evaluate(async () => { await document.fonts.ready })
  const assert = async (selector) => { if (!await page.$(selector)) throw Error(`Missing ${selector}`) }
  const capture = async (filename) => {
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1)
    if (overflow) throw Error(`Horizontal overflow at ${filename}`)
    await page.screenshot({ path: `${output}/${filename}.png`, fullPage: false })
    console.log(`${filename}.png`)
  }
  await assert('[data-testid="plan-pulse"]')
  await assert('[data-testid="plan-review"]')
  await capture('15-desktop-plan')
  await page.click('[data-testid="plan-pulse"]')
  await assert('[data-testid="schedule-detail-modal"]')
  await capture('16-desktop-detail')
  await page.click('[data-testid="modal-history-tab"]')
  await page.waitForSelector('[data-testid="schedule-modal-body"]')
  await capture('17-desktop-history')
  await page.click('[aria-label="关闭详情"]')
  await page.waitForSelector('[data-testid="dialog-overlay"]', { hidden: true })
  await page.click('[data-testid="scheduled-message-badge"]')
  await page.waitForSelector('[data-testid="schedule-detail-modal"]', { visible: true })
  await capture('18-desktop-from-message')
  await page.click('[aria-label="关闭详情"]')
  await page.waitForSelector('[data-testid="dialog-overlay"]', { hidden: true })
  await page.click('[data-testid="schedule-new"]')
  await assert('[data-testid="schedule-rule-editor"]')
  await capture('19-desktop-rules')
  await page.click('[aria-label="关闭编辑器"]')
  await page.waitForSelector('[data-testid="dialog-overlay"]', { hidden: true })
  await page.click('[data-testid="scope-workspace"]')
  await assert('[data-testid="plan-check"]')
  await capture('20-desktop-workspace')
  await page.click('[data-testid="scope-session"]')
  await page.click('[data-testid="schedule-inbox-trigger"]')
  await assert('[data-testid="schedule-inbox"]')
  const inboxWithinViewport = await page.$eval('[data-testid="schedule-inbox"]', (node) => { const rect = node.getBoundingClientRect(); return rect.left >= 0 && rect.right <= innerWidth && rect.top >= 0 && rect.bottom <= innerHeight })
  if (!inboxWithinViewport) throw Error('Inbox is clipped by the viewport')
  await capture('21-desktop-inbox')
  await page.click('[data-testid="schedule-inbox-trigger"]')
  await page.setViewport({ width: 820, height: 1100, deviceScaleFactor: 1 })
  await capture('22-tablet-plan')
  await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 1 })
  await capture('23-mobile-plan')
  await page.click('[data-testid="schedule-inbox-trigger"]')
  await assert('[data-testid="schedule-inbox"]')
  await capture('24-mobile-inbox')
  await page.click('[data-testid="schedule-inbox-trigger"]')
  await page.click('[data-testid="plan-pulse"]')
  await page.click('[data-testid="modal-history-tab"]')
  await capture('25-mobile-history')
  if (errors.length) throw Error(`Browser runtime errors: ${errors.join(' | ')}`)
  console.log('All prototype screenshots passed interaction, privacy-origin and overflow checks.')
} finally {
  await browser.close()
}
